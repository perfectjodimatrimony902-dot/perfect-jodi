export function getProfilePhoto(
  idOrProfile?: { id?: string; gender?: string; photoUrl?: string } | string,
): string {
  if (!idOrProfile) return FEMALE_POOL[0]!;
  if (typeof idOrProfile === "object") {
    if (idOrProfile.photoUrl) return idOrProfile.photoUrl;
    if (idOrProfile.id && PROFILE_PHOTOS[idOrProfile.id]?.main) {
      return PROFILE_PHOTOS[idOrProfile.id]!.main;
    }
    const pool = idOrProfile.gender === "male" ? MALE_POOL : FEMALE_POOL;
    const hash = (idOrProfile.id || "default")
      .split("")
      .reduce((acc, c) => acc + c.charCodeAt(0), 0);
    return pool[hash % pool.length]!;
  }
  if (PROFILE_PHOTOS[idOrProfile]?.main) return PROFILE_PHOTOS[idOrProfile]!.main;
  return FEMALE_POOL[0]!;
}

export function getProfileGallery(id: string): string[] {
  if (PROFILE_PHOTOS[id]?.gallery) return PROFILE_PHOTOS[id]!.gallery;
  const photo = getProfilePhoto(id);
  return [photo];
}
